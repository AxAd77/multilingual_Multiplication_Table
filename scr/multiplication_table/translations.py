def get_translation(language, key):
    """Return the translation for the selected language."""
    language_translations = TRANSLATIONS.get(language, TRANSLATIONS["en"])
    return language_translations.get(key, TRANSLATIONS["en"].get(key, key))


def get_language_name(language_code):
    """Return the native name of the selected language."""
    return LANGUAGE_NAMES.get(language_code, LANGUAGE_NAMES["en"])
